"""
Instrument 1 baseline-vs-CEO similarity for all six models, with the paper's
Figure 2 method (i1_baseline_vs_ceo in plot_response_results.py): per model and
question, mean all-MiniLM-L6-v2 embedding of the baseline runs vs mean embedding
of the CEO runs, cosine similarity. Plain answer text via get_answer_text.

Also reads the five-model values from the existing Figure 2
(results/instrument_1/similarity_baseline_vs_ceo.html) to check the reproduction.
The figure itself is not regenerated.

Writes results/stats/i1_role_similarity.md. No API calls; the embedding model
loads from the local cache.

Usage:
    python scripts/stats_i1_role_similarity.py
"""

import os
import sys

os.environ.setdefault("HF_HUB_OFFLINE", "1")
sys.modules["torchvision"] = None   # torch/torchvision mismatch; not needed here

from pathlib import Path

import numpy as np
from sentence_transformers import SentenceTransformer

import plot_response_results as prp
from stats_i5 import MODELS, plotly_traces

OUT_FILE = Path("results/stats/i1_role_similarity.md")
OLD_FIG  = Path("results/instrument_1/similarity_baseline_vs_ceo.html")
DIMS     = {"I1_Q1": "legal certainty", "I1_Q2": "accountability", "I1_Q3": "enforceability"}


def role_similarity(i1: dict, embed: SentenceTransformer) -> dict:
    """{(model, q): cosine(mean baseline embedding, mean CEO embedding)}, as Figure 2."""
    out = {}
    for q in DIMS:
        for m in MODELS:
            b = prp.get_responses(i1, m, "baseline", q)
            c = prp.get_responses(i1, m, "ceo", q)
            out[(m, q)] = prp.cosine_sim(prp.avg_embedding(b, embed), prp.avg_embedding(c, embed))
    return out


if __name__ == "__main__":
    i1 = prp._try_load("instrument_1")
    sim = role_similarity(i1, SentenceTransformer(prp.EMBEDDING_MODEL))

    trace = plotly_traces(OLD_FIG)[0]
    old = {(lab, q): v for q, row in zip(DIMS, trace["z"]) for lab, v in zip(trace["x"], row)}
    label = {m: prp.MODEL_LABELS.get(m, m) for m in MODELS}
    fig_dev = max(abs(sim[(m, q)] - old[(label[m], q)]) for m in MODELS for q in DIMS
                  if (label[m], q) in old)
    n_fig = sum((label[m], q) in old for m in MODELS for q in DIMS)

    f3 = lambda v: f"{v:.3f}"
    mean_m = {m: float(np.mean([sim[(m, q)] for q in DIMS])) for m in MODELS}
    five = [sim[(m, q)] for m in MODELS[:5] for q in DIMS]
    six = list(sim.values())
    ranked = sorted(sim.items(), key=lambda kv: kv[1])

    md = ["# I1 baseline vs CEO similarity, six models", "",
          "Generated by `scripts/stats_i1_role_similarity.py`. Figure 2 method "
          "(i1_baseline_vs_ceo): cosine of mean all-MiniLM-L6-v2 embeddings, baseline runs 1-3 vs "
          "CEO runs 1-3, per model and question.", "",
          "| Model | " + " | ".join(DIMS.values()) + " | mean | Figure 2 (legal certainty / accountability / enforceability) |",
          "|---|" + "---|" * (len(DIMS) + 2)]
    for m in MODELS:
        figv = " / ".join(f3(old[(label[m], q)]) if (label[m], q) in old else "—" for q in DIMS)
        md.append(f"| {m} | " + " | ".join(f3(sim[(m, q)]) for q in DIMS) + f" | {f3(mean_m[m])} | {figv} |")
    md.append("| mean | " + " | ".join(f3(np.mean([sim[(m, q)] for m in MODELS])) for q in DIMS)
              + f" | {f3(np.mean(six))} | |")
    md += ["", "| Range | min | max |", "|---|---|---|",
           f"| five original models | {f3(min(five))} | {f3(max(five))} |",
           f"| six models | {f3(min(six))} | {f3(max(six))} |", "",
           "| Largest shifts (lowest similarity) | similarity |", "|---|---|"]
    for (m, q), v in ranked[:5]:
        md.append(f"| {m}, {DIMS[q]} | {f3(v)} |")
    md += ["", "| Models by mean similarity (most stable first) | mean | min |", "|---|---|---|"]
    for m in sorted(MODELS, key=lambda m: -mean_m[m]):
        md.append(f"| {m} | {f3(mean_m[m])} | {f3(min(sim[(m, q)] for q in DIMS))} |")
    md += ["", f"Reproduction vs Figure 2 ({n_fig} cells): max absolute deviation {fig_dev:.2e}.", ""]
    OUT_FILE.write_text("\n".join(md), encoding="utf-8")
    print(OUT_FILE.read_text(encoding="utf-8"))
