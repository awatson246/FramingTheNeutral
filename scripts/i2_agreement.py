"""
Agreement for the I2 criterion codes (data/processed/i2_codes.json). No API calls.

Unit: one criterion of one answer (answer_id, n). Codes: met / not_addressed /
contradicted; binary collapses to met vs not met.
  coder vs coder   claude-sonnet vs gpt-6.1-sol, all units both coded
  human vs coder   the author's hand codes in data/processed/manual_review.json
                   (6 answers; "none" = not_addressed) vs each coder
Per pair: n units, percent agreement, Cohen's kappa (3-category and binary), and
the 3-category confusion matrix. Also code counts per coder and a flag tally.

Writes results/stats/i2_coder_agreement.csv and .md.

Usage:
    python scripts/i2_agreement.py
"""

import csv
import json
from collections import Counter
from pathlib import Path

CODES_FILE  = Path("data/processed/i2_codes.json")
REVIEW_FILE = Path("data/processed/manual_review.json")
OUT_DIR     = Path("results/stats")
CODES       = ["met", "not_addressed", "contradicted"]
HUMAN_MAP   = {"met": "met", "none": "not_addressed", "not_addressed": "not_addressed",
               "contradicted": "contradicted"}


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def coder_units(codes: dict) -> dict:
    """{coder: {(answer_id, n): code}}"""
    out = {}
    for coder, models in codes.items():
        units = out.setdefault(coder, {})
        for conds in models.values():
            for runs in conds.values():
                for scen in runs.values():
                    for cell in scen.values():
                        for c in (cell.get("parsed") or {}).get("codes", []):
                            units[(cell["answer_id"], c["n"])] = c["code"]
    return out


def human_units(review: dict) -> dict:
    return {(a["answer_id"], c["n"]): HUMAN_MAP[c["code"]]
            for a in review["coding"] for c in a["codes"]}


def kappa(a: list, b: list, cats: list) -> float:
    n = len(a)
    po = sum(x == y for x, y in zip(a, b)) / n
    ca, cb = Counter(a), Counter(b)
    pe = sum(ca[k] * cb[k] for k in cats) / n ** 2
    return float("nan") if pe == 1 else (po - pe) / (1 - pe)


def agreement(name: str, x: dict, y: dict) -> dict:
    keys = sorted(set(x) & set(y))
    a, b = [x[k] for k in keys], [y[k] for k in keys]
    ab, bb = [v == "met" for v in a], [v == "met" for v in b]
    return {"pair": name, "n_units": len(keys),
            "n_answers": len({k[0] for k in keys}),
            "only_in_first": len(set(x) - set(y)), "only_in_second": len(set(y) - set(x)),
            "pct_agree_3": 100 * sum(p == q for p, q in zip(a, b)) / len(keys),
            "kappa_3": kappa(a, b, CODES),
            "pct_agree_bin": 100 * sum(p == q for p, q in zip(ab, bb)) / len(keys),
            "kappa_bin": kappa(ab, bb, [True, False]),
            "confusion": {p: {q: sum(1 for u, v in zip(a, b) if u == p and v == q)
                              for q in CODES} for p in CODES}}


def flag_tally(codes: dict) -> dict:
    out = {}
    for coder, models in codes.items():
        t = Counter()
        for conds in models.values():
            for runs in conds.values():
                for scen in runs.values():
                    for cell in scen.values():
                        t.update(f.split(":")[0] for f in cell["flags"])
        out[coder] = dict(t)
    return out


if __name__ == "__main__":
    codes = load(CODES_FILE)["codes"]
    units = coder_units(codes)
    human = human_units(load(REVIEW_FILE))
    c1, c2 = "claude-sonnet", "gpt-6.1-sol"

    rows = [agreement(f"{c1} vs {c2}", units[c1], units[c2]),
            agreement(f"author vs {c1}", human, units[c1]),
            agreement(f"author vs {c2}", human, units[c2])]
    counts = {name: Counter(u.values()) for name, u in
              [(c1, units[c1]), (c2, units[c2]), ("author (6 answers)", human)]}
    flags = flag_tally(codes)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    cols = ["pair", "n_answers", "n_units", "only_in_first", "only_in_second",
            "pct_agree_3", "kappa_3", "pct_agree_bin", "kappa_bin"]
    with open(OUT_DIR / "i2_coder_agreement.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for r in rows:
            w.writerow({c: (f"{r[c]:.6g}" if isinstance(r[c], float) else r[c]) for c in cols})

    md = ["# I2 criterion codes: agreement", "",
          "Generated by `scripts/i2_agreement.py` from data/processed/i2_codes.json "
          "(criteria: i2_criteria_v1.json). Unit = one criterion of one answer. "
          "Binary = met vs not met.", "",
          "## Code counts", "", "| Coder | met | not_addressed | contradicted | total |",
          "|---|---|---|---|---|"]
    for name, c in counts.items():
        md.append(f"| {name} | " + " | ".join(str(c[k]) for k in CODES) + f" | {sum(c.values())} |")
    md += ["", "## Agreement", "",
           "| Pair | answers | units | % agree (3) | kappa (3) | % agree (binary) | kappa (binary) |",
           "|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['pair']} | {r['n_answers']} | {r['n_units']} | {r['pct_agree_3']:.1f} | "
                  f"{r['kappa_3']:.3f} | {r['pct_agree_bin']:.1f} | {r['kappa_bin']:.3f} |")
    for r in rows:
        first, second = r["pair"].split(" vs ")
        md += ["", f"### Confusion: {r['pair']} (rows {first}, columns {second})", "",
               "| | " + " | ".join(CODES) + " |", "|---|" + "---|" * len(CODES)]
        for p in CODES:
            md.append(f"| {p} | " + " | ".join(str(r["confusion"][p][q]) for q in CODES) + " |")
    md += ["", "## Flags per coder (cells)", ""]
    md += [f"- {coder}: " + (", ".join(f"{k} {v}" for k, v in sorted(t.items())) or "none")
           for coder, t in flags.items()]
    (OUT_DIR / "i2_coder_agreement.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print((OUT_DIR / "i2_coder_agreement.md").read_text(encoding="utf-8"))
